-- Поиск клиента кабинета по сети, в которую попадает адрес потока.
--
-- Раньше это был перебор: каталог привязок собирался в массив и на каждой
-- строке потока просматривался целиком через arrayFirst с isIPAddressInRange.
-- На установке с 19 тысячами привязок такой запрос не просто медленный — он
-- не выполняется вовсе, запрашивая 54 ГиБ памяти при разрешённых 42 ГиБ.
-- Словарь IP_TRIE ищет по дереву префиксов за одно обращение: то же окно на
-- 36 миллионов строк отдаётся за 3.4 секунды.
--
-- Побочно меняется ответ на вложенных сетях. Перебор возвращал первую
-- подходящую сеть в порядке строк каталога, то есть при вложенных /8 и /24
-- ответ зависел от порядка и был произволен. Словарь всегда отдаёт самую
-- точную сеть, и более конкретная привязка выигрывает.

-- Источник: одна строка на сеть. Привязки уже ограничены клиентами с режимом
-- 'prefixes' и включёнными записями, но одна и та же сеть могла быть заведена
-- дважды — ключ словаря обязан быть уникальным, поэтому группируем.
CREATE OR REPLACE VIEW default.net_client_prefix_dict_src AS
SELECT
    prefix,
    min(client_id) AS client_id
FROM default.net_client_prefixes_enabled
WHERE prefix != ''
GROUP BY prefix;

-- Срок жизни задан намеренно: принудительная перезагрузка словаря требует
-- гранта SYSTEM RELOAD DICTIONARY, которого у пользователей интерфейса нет,
-- поэтому новые привязки должны подхватываться сами. Источник маленький
-- (десятки тысяч строк), перечитывать его раз в минуту недорого.
CREATE DICTIONARY IF NOT EXISTS default.net_client_prefix_dict
(
    `prefix` String,
    `client_id` String
)
PRIMARY KEY prefix
SOURCE(CLICKHOUSE(HOST '${CH_DICT_HOST}' PORT ${CH_DICT_PORT} USER '${CH_DICT_USER}' PASSWORD '${CH_DICT_PASSWORD}' DB 'default' TABLE 'net_client_prefix_dict_src' CONNECT_TIMEOUT 10 SEND_RECEIVE_TIMEOUT 30))
LIFETIME(MIN 30 MAX 90)
LAYOUT(IP_TRIE);
